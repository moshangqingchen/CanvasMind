import { expect, test } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { installAssistantFixture, assistantCanvasId, assistantModelKey } from "./helpers/assistant-fixture";
import { agentPanel, expectAgentModel } from "./helpers/agent-controls";

for (const theme of ["dark", "light"] as const) test(`${theme} 合一输入与真实参数控件，切换渠道并原样放入画布`, async ({ page }) => {
  const fixture = await installAssistantFixture(page, { theme, motion: false, channelParameters: true });
  await page.goto(`/canvas/${assistantCanvasId}`);
  await page.getByRole("button", { name: "打开智能体", exact: true }).click();
  await expectAgentModel(page, assistantModelKey);
  const panel = agentPanel(page);
  await expect(panel.getByRole("group", { name: "对话方式", exact: true })).toHaveCount(0);
  await panel.getByRole("textbox", { name: "创作任务要求", exact: true }).fill("请制作一张秋日活动海报，先给我待确认方案。");
  await panel.getByRole("button", { name: "发送任务", exact: true }).click();
  await expect(panel.getByTestId("agent-stream-output")).toBeVisible();
  const materialize = panel.getByRole("button", { name: "放入画布", exact: true });
  await expect(materialize).toBeEnabled();
  expect(fixture.turns).toHaveLength(1);
  expect(fixture.turns[0]!.intent).toBe("auto");
  expect(fixture.calls.map(call => call.action)).toEqual(["turn:auto"]);
  expect(fixture.canvas.graph.nodes).toHaveLength(2);
  const card = panel.locator('article[class*="productionCard"]');
  await card.locator('details[class*="planStep"] > summary').click();
  const controls = card.getByRole("group", { name: "秋日主视觉 渠道与参数", exact: true });
  await expect(controls.getByLabel("画面比例", { exact: true })).toHaveValue("9:16");
  await expect(controls.getByRole("group", { name: "自动与输出分辨率快捷档位", exact: true }).getByRole("button", { name: "4K", exact: true })).toHaveAttribute("aria-pressed", "true");
  await controls.getByLabel("秋日主视觉 供应商", { exact: true }).selectOption("fixture-image-b");
  await expect(controls.getByLabel("画面比例", { exact: true })).toHaveValue("9:16");
  await expect(controls.getByRole("group", { name: "自动与输出分辨率快捷档位", exact: true }).getByRole("button", { name: "2K", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(controls.getByLabel("质量", { exact: true })).toHaveValue("standard");
  await expect(controls.getByRole("status")).toContainText("已按所选型号的合法默认值调整");
  await controls.getByLabel("种子", { exact: true }).fill("77");
  await controls.getByRole("combobox", { name: "秋日主视觉 执行模型", exact: true }).click();
  await expect(page.getByRole("listbox", { name: "秋日主视觉 执行模型 可选模型", exact: true })).toContainText("fixture.image.full-id-b");
  await page.keyboard.press("Escape");
  const output = resolve(fileURLToPath(new URL("../../../..", import.meta.url)), process.env.NEURAL_EVIDENCE_DIR ?? ".codex-logs/2026-10-16-redesign-v2/out", "assistant");
  await mkdir(output, { recursive: true });
  await page.screenshot({ path: join(output, `${theme}-unified-plan-parameters.png`) });
  await expect(materialize).toBeDisabled();
  await card.getByRole("button", { name: "保存方案修改", exact: true }).click();
  await expect(materialize).toBeEnabled();
  const saved = fixture.sessions.get("assistant-session-main")!.plans[0]!.proposal.calls[0]!;
  expect(saved).toMatchObject({ preferredConnectionId: "assistant-image-b", preferredModelId: "fixture.image.full-id-b", parameters: { aspect_ratio: "9:16", resolution: "2K", quality: "standard", seed: 77 } });
  await materialize.click();
  await expect(page.locator('.react-flow__node[data-id="assistant-generated"]')).toBeVisible();
  const generated = fixture.canvas.graph.nodes.find(node => (node as { id?: string }).id === "assistant-generated") as { data: Record<string, unknown> };
  expect(generated.data).toMatchObject({ connectionId: saved.preferredConnectionId, model: saved.preferredModelId, parameters: saved.parameters });
  expect(generated.data.parameters).toEqual(saved.parameters);
  await panel.getByRole("button", { name: "关闭智能体", exact: true }).click();
  await page.getByRole("button", { name: "打开 秋日主视觉 模型与参数", exact: true }).click();
  const nodePanel = page.getByRole("dialog", { name: "秋日主视觉 模型与参数", exact: true });
  await expect(nodePanel.getByRole("combobox", { name: "秋日主视觉 模型", exact: true })).toContainText("fixture.image.full-id-b");
  for (const [label, value] of [["画面比例", "9:16"], ["质量", "standard"], ["种子", "77"]]) await expect(nodePanel.getByLabel(label!, { exact: true })).toHaveValue(value!);
  await expect(nodePanel.getByRole("group", { name: "自动与输出分辨率快捷档位", exact: true }).getByRole("button", { name: "2K", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.screenshot({ path: join(output, `${theme}-materialized-node-parameters.png`) });
  expect(fixture.calls.map(call => call.action)).toEqual(["turn:auto", "update", "materialize"]);
  fixture.assertSafe();
});
